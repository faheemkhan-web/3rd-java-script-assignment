// =====================================
//       Arithmetic Operators
// =====================================

// Declaring two number variables
let a = 10;
let b = 3;

// Addition
console.log("Addition (a + b):", a + b);

// Subtraction
console.log("Subtraction (a - b):", a - b);

// Multiplication
console.log("Multiplication (a * b):", a * b);

// Division
console.log("Division (a / b):", a / b);

// Modulus (remainder)
console.log("Modulus (a % b):", a % b);


// =====================================
//      Assignment Operators
// =====================================

let num = 20; 
console.log("Initial value:", num);

// += adds value to the variable
num += 5;
console.log("After += 5:", num);

// -= subtracts value from the variable
num -= 3;
console.log("After -= 3:", num);

// *= multiplies the variable value
num *= 2;
console.log("After *= 2:", num);

// /= divides the variable value
num /= 4;
console.log("After /= 4:", num);


// =====================================
//        Comparison Operators
// =====================================

let x = 10;
let y = "10";

console.log("x == y:", x == y);   // true (value is same)
console.log("x === y:", x === y); // false (type is different)
console.log("x != y:", x != y);   // false
console.log("x > 5:", x > 5);     // true
console.log("x < 20:", x < 20);   // true
console.log("x >= 10:", x >= 10); // true
console.log("x <= 9:", x <= 9);   // false


// =====================================
//        Expressions
// =====================================

// Total price expression
let price = 500;
let quantity = 3;
let totalPrice = price * quantity;

console.log("Total Price:", totalPrice);

// Final score expression
let marks1 = 75;
let marks2 = 80;
let marks3 = 70;

let finalScore = marks1 + marks2 + marks3;
console.log("Final Score:", finalScore);




let numStr = "10";
let numVal = 10;

console.log("'10' == 10:", numStr == numVal);
console.log("'10' === 10:", numStr === numVal);


